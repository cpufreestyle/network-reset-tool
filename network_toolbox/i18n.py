def _app_data_dir():
    base = os.environ.get("LOCALAPPDATA") or os.path.expanduser("~")
    d = os.path.join(base, "NetworkResetTool")
    try:
        os.makedirs(d, exist_ok=True)
    except Exception:
        pass
    return d


def lang_path():
    """语言偏好文件路径(与 theme.txt / monitor/ 一致，放应用数据目录)。"""
    return os.path.join(_app_data_dir(), "lang.txt")


def current_lang():
    """读取持久化的语言名; 没有记录/读失败/不认识的语言都回落默认中文。"""
    global _lang
    if _lang is not None:
        return _lang
    try:
        with open(lang_path(), "r", encoding="utf-8") as f:
            name = f.read().strip().lower()
        if name in LANGS:
            _lang = name
            return _lang
    except Exception:
        pass
    _lang = DEFAULT_LANG
    return _lang


def set_lang(name, persist=True):
    """切换语言; 返回实际生效的语言名。非法值落回默认。

    `persist=False` 只改本次进程的语言、不写 lang.txt——
    给`--lang en` 这类一次性的命令行指令用，不该善自改掉用户存的偏好。
    """
    global _lang
    if name not in LANGS:
        name = DEFAULT_LANG
    _lang = name
    if persist:
        try:
            with open(lang_path(), "w", encoding="utf-8") as f:
                f.write(name)
        except Exception:
            pass  # 写不进去(只读目录/UAC)也不影响本次生效
    return name


def tr(text):
    """翻译一段文案。英文目录里没有就原样返回(即中文)。"""
    if not isinstance(text, str):
        return text
    if current_lang() == "zh":
        return text
    return EN.get(text, text)


def tr_f(template, **kw):
    """带占位符的文案：`tr_f("已切换到 {x}", x=name)`。

    目录里的英文翻译同样用 {x} 占位，所以中英文模板可以一一对应；
    字典里没有这条模板时退回用中文模板直接 format，不会 KeyError。
    """
    if not isinstance(template, str):
        return template
    if current_lang() == "zh":
        return template.format(**kw)
    return EN.get(template, template).format(**kw)
